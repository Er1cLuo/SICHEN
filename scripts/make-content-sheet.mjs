const HEAD = ['序号', '页面 / 位置', '字段', '当前占位内容（参考）', '建议字数', '你的内容（请在此列填写）'];
const WIDTHS = [6, 18, 20, 52, 14, 46];

/** 通用建表 */
function addSheet(wb, name, rows, note) {
  const ws = wb.addWorksheet(name, {
    views: [{ state: 'frozen', ySplit: 1 }],
    pageSetup: { fitToPage: true, orientation: 'landscape' },
  });
  ws.columns = WIDTHS.map((w, i) => ({ width: w, key: HEAD[i] }));
  const head = ws.addRow(HEAD);
  head.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  head.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1F1F24' } };
  head.alignment = { vertical: 'middle' };
  head.height = 22;

  rows.forEach((r, i) => {
    const row = ws.addRow([i + 1, r[0], r[1], r[2] ?? '', r[3] ?? '', '']);
    row.alignment = { vertical: 'top', wrapText: true };
    // 待填写列为浅色底，方便识别
    row.getCell(6).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFFF8E1' } };
  });

  if (note) {
    const n = ws.addRow([]);
    n.getCell(1).value = note;
    n.getCell(1).font = { italic: true, color: { argb: 'FF7A7A7A' } };
  }
  return ws;
}

